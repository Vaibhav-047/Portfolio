from pathlib import Path
import re
from playwright.sync_api import sync_playwright, expect

out = Path('test-results/manga')
out.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    context = browser.new_context(viewport={'width': 1440, 'height': 1000}, permissions=['clipboard-read', 'clipboard-write'])
    page = context.new_page()
    errors, failed = [], []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('response', lambda r: failed.append(f'{r.status}: {r.url}') if r.status >= 400 else None)
    page.goto('http://127.0.0.1:5173/', wait_until='networkidle')
    expect(page).to_have_title('Vaibhav Tripathi — The Next Page')
    expect(page.locator('h1')).to_contain_text('SMALL START.')
    assert page.evaluate("async () => {const i=new Image();i.src='/manga/origin-panels.png';await i.decode();return i.naturalWidth>=1536}")
    page.screenshot(path=str(out / 'desktop-hero.png'))
    page.get_by_role('link', name='Turn the first page').click()
    expect(page).to_have_url(re.compile('#origin$'))
    page.locator('#training').scroll_into_view_if_needed()
    page.get_by_role('button', name='Unlock next lesson').click()
    expect(page.locator('.training-interaction [role="status"]')).to_contain_text('1 of 5')
    page.locator('.hold-training').focus()
    page.keyboard.down('Space')
    page.wait_for_timeout(1250)
    page.keyboard.up('Space')
    expect(page.locator('.training-interaction [role="status"]')).to_contain_text('2 of 5')
    page.locator('#training').screenshot(path=str(out / 'training.png'))
    page.get_by_role('button', name='Broken layout').drag_to(page.locator('.patch-tray'))
    page.get_by_role('button', name='Silent button').click()
    page.get_by_role('button', name='Missing focus').click()
    expect(page.locator('.bug-board [role="status"]')).to_contain_text('3/3 patches made')
    page.get_by_role('button', name='Read Supremo AI project details').click()
    expect(page.get_by_role('dialog')).to_be_visible()
    expect(page).to_have_url(re.compile('project=supremo-ai'))
    page.keyboard.press('Escape')
    expect(page.get_by_role('dialog')).to_have_count(0)
    expect(page.get_by_role('button', name='Read Supremo AI project details')).to_be_focused()
    page.get_by_role('button', name='Copy email', exact=True).click()
    expect(page.get_by_role('button', name='Email copied')).to_be_visible()
    assert page.evaluate('navigator.clipboard.readText()') == 'raunaktripathi047@gmail.com'
    page.get_by_role('button', name='Motion full').click()
    expect(page.locator('html')).to_have_attribute('data-manga-motion', 'reduced')
    page.reload(wait_until='networkidle')
    expect(page.locator('html')).to_have_attribute('data-manga-motion', 'reduced')
    page.get_by_role('button', name='Just the facts').click()
    expect(page.locator('.recruiter-sheet')).to_contain_text('Vaibhav Tripathi')
    expect(page.locator('#cover')).to_have_count(0)
    page.evaluate('window.print = () => window.didPrint = true')
    page.get_by_role('button', name='Print / Save PDF').click()
    assert page.evaluate('window.didPrint')
    page.emulate_media(media='print')
    page.screenshot(path=str(out / 'resume-print.png'), full_page=True)
    page.emulate_media(media='screen')
    page.get_by_role('button', name='Read the story', exact=True).first.click()
    for width in [320, 390, 768, 1440]:
        page.set_viewport_size({'width': width, 'height': 844})
        page.wait_for_timeout(150)
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), f'Overflow at {width}'
    page.set_viewport_size({'width': 390, 'height': 844})
    page.get_by_role('button', name='Open navigation').click()
    page.get_by_role('link', name='The work', exact=True).click()
    expect(page).to_have_url(re.compile('#missions$'))
    expect(page.get_by_role('button', name='Open navigation')).to_have_attribute('aria-expanded', 'false')
    page.get_by_role('button', name='Open navigation').click()
    page.keyboard.press('Escape')
    expect(page.get_by_role('button', name='Open navigation')).to_have_attribute('aria-expanded', 'false')
    page.evaluate('window.scrollTo(0, 0)')
    page.wait_for_timeout(100)
    page.screenshot(path=str(out / 'mobile.png'), full_page=True)
    page.goto('http://127.0.0.1:5173/?project=khoj-ai', wait_until='networkidle')
    expect(page.get_by_role('dialog')).to_contain_text('Khoj AI')
    page.keyboard.press('Escape')
    reduced = browser.new_context(reduced_motion='reduce')
    other = reduced.new_page()
    other.goto('http://127.0.0.1:5173/', wait_until='networkidle')
    expect(other.locator('html')).to_have_attribute('data-manga-motion', 'reduced')
    assert errors == [], errors
    assert failed == [], failed
    browser.close()
    print('PASS: original art loads; chapter navigation; hold/keyboard lesson unlocking; drag and tap debugging; project dialogs, deep links and focus restoration; clipboard; persisted/system reduced motion; resume/print action; mobile menu/Escape; no overflow at 320/390/768/1440; no runtime or HTTP errors.')
